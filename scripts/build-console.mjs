import { build } from 'esbuild';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
const result = await build({entryPoints:['apps/console/src/main.tsx'],bundle:true,write:false,outdir:'console',format:'esm',platform:'browser',target:'es2022',minify:true,jsx:'automatic',define:{'process.env.NODE_ENV':'"production"'}});
const js = result.outputFiles.find(file=>file.path.endsWith('.js'))?.text;
const css = result.outputFiles.find(file=>file.path.endsWith('.css'))?.text;
if (!js || !css) throw new Error('Console build did not produce both local assets');
const html = await readFile('apps/console/index.html','utf8');
await mkdir('apps/worker/src/generated',{recursive:true});
await writeFile('apps/worker/src/generated/console.ts', '// Generated by scripts/build-console.mjs. Do not edit.\n'+Object.entries({CONSOLE_HTML:html,CONSOLE_JS:js,CONSOLE_CSS:css}).map(([name,value])=>`export const ${name} = ${JSON.stringify(value)};`).join('\n')+'\n');
